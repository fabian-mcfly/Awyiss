/**
 * @property \Authentication\Controller\Component\AuthenticationComponent $Authentication
 * @property \Awyiss\Controller\Component\AuthorizationComponent $Authorization
 * @property \Awyiss\Controller\Component\CategoriesComponent $Categories
 * @property \Awyiss\Controller\Component\LockComponent $Lock
 * @property \Awyiss\Controller\Component\PaginateComponent $Paginate
 * @property \Awyiss\Controller\Component\SearchComponent $Search
 * @property \Awyiss\Controller\Component\SystemOrderComponent $SystemOrder
 */
abstract class BackendController extends AppController {
	use IdentityAwareTrait;


	/**
	 * @see AuthorizationComponent
	 * @var array Settings for the AuthorizationComponent
	 */
	protected array $authorization = [];
	/**
	 * @see CategoriesComponent
	 * @var array Settings for the CategoriesComponent
	 */
	protected array $categories = [];
	/**
	 * @var array<string> A list of properties that will be merged with values from the database configuration
	 */
	protected array $customConfigProperties = [
		'categories',
		'eventTrigger',
		'paginate',
		'publicationData',
		'systemOrder',
	];
	/**
	 * @see \Awyiss\Controller\Component\EventTriggerComponent
	 * @var array Settings for the EventTriggerComponent
	 */
	protected array $eventTrigger = [];
	/**
	 * @see \Awyiss\Controller\Component\LockComponent
	 * @var array Settings for the LockComponent
	 */
	protected array $lock = [];
	/**
	 * @see initializeOverviewWhere()
	 * @var array Settings used in initializeOverviewWhere()
	 */
	protected array $overviewWhere;
	/**
	 * @inheritDoc
	 * @var array
	 */
	protected array $paginate = [
		'enabled' => false,
	];
	/**
	 * @var array Settings for the PublicationDataBehavior
	 */
	protected array $publicationData = [];
	/**
	 * @see SearchComponent
	 * @var array Settings for the SearchComponent
	 */
	protected array $search = [];
	/**
	 * @see SystemOrderComponent
	 * @var array Settings for the SystemOrderComponent
	 */
	protected array $systemOrder = [];


	/**
	 * @throws \Exception
	 */
	public function initialize(): void {
		parent::initialize();

		// Load the user configuration
		Awyiss::loadUserConfiguration();

		//Load event listeners for the current controller in the "backend"-folder
		EventListenersProvider::loadListener($this->getName(), Awyiss::REALM_BACKEND);

		//Merge the config properties with custom configuration from the database
		$scope = $this->getName();

		foreach ($this->customConfigProperties as $property) {
			$path = implode('.', ['Awyiss', $scope, Awyiss::REALM_BACKEND, $property]);
			$customConfig = Configure::read($path);
			if ($customConfig && is_array($this->$property)) {
				$this->$property = Hash::merge($this->$property, $customConfig);
			}
		}

		$request = Router::getRequest();
		if ($request) {
			$path = $request->getUri()->getPath();

			$languageShortcode = LocaleMiddleware::getLanguage()->shortcode;

			$parts = [
				'lang' => $request->getParam('lang'),
				'controller' => $request->getParam('controller'),
				'action' => $request->getParam('action'),
				'_name' => Awyiss::REALM_BACKEND,
			];
			$parts += $request->getParam('parts');

			if ($request->getParam('prefix') !== 'Backend') {
				$prefixParts = explode('/', $request->getParam('prefix'));
				array_shift($prefixParts);

				$prefixName = implode('_', $prefixParts);
				$prefixName .= '_' . $request->getParam('controller');
				$prefixName = strtolower($prefixName);

				$parts['_name'] = Awyiss::REALM_BACKEND . '::' . $prefixName;
			}

			//Redirect if the url does not match the one generated by Router::url(), for example when the controller action is omitted.
			$testPath = Router::url($parts);
			if (!str_starts_with($request->getAttribute('base') . DS . ltrim($path, DS), $testPath)) {
				$this->redirect(
					Router::url(
						[
							'_name' => $parts['_name'],
							'_base' => false,
							'?' => $request->getQueryParams(),
						] + $request->getParam('parts') + ['lang' => $languageShortcode]
					),
					301
				);
			}

			//Redirect to the same route if the last character is not a slash
			if (!$request->getParam('fullSlug') && !str_ends_with($path, '/') && !$request->getParam('parts')) {
				$this->redirect($path . '/', 301);
			}

			$this->loadComponent('Authentication.Authentication', [
				'identityAttribute' => Awyiss::REALM_BACKEND . 'Identity',
			]);

			$this->loadComponent('Authorization', $this->authorization);

			$this->loadComponent('EventTrigger', $this->eventTrigger);

			$this->loadComponent('Flash', ['key' => '*']);

			if ($this->defaultTable) {
				$this->loadComponent('Categories', $this->categories);

				$this->loadComponent('Lock', $this->lock);

				$this->loadComponent('Search', $this->search);

				$this->loadComponent('SystemOrder', $this->systemOrder);
			}

			$this->loadComponent('Paginate', $this->paginate);
		}

		//Detect the available commands
		if (!Configure::read('AvailableCommands')) {
			/** @var \Queue\Model\Table\QueuedJobsTable $queuedJobsTable */
			$queuedJobsTable = $this->fetchTable('Queue.QueuedJobs');
			if (!$queuedJobsTable->isQueued('system::detect_available_commands')) {
				$queuedJobsTable->createJob('Queue.Execute', [
					'command' => 'bin' . DS . 'cake media detect_available_commands',
					'log' => true,
				], [
					'group' => 'general',
					'priority' => 1,
					'reference' => 'system::detect_available_commands',
				]);
			}
		}

		//Sets the name of the viewClass to be used by the viewBuilder
		$this->viewBuilder()->setClassName(BackendView::class);
	}


	/**
	 * @inheritDoc
	 * @param \Cake\Datasource\RepositoryInterface|\Cake\Datasource\QueryInterface|string|null $object
	 * @param array $settings
	 * @return \Cake\Datasource\Paging\PaginatedInterface
	 */
	public function paginate(
		RepositoryInterface|QueryInterface|string|null $object = null,
		array $settings = []
	): PaginatedInterface {
		return $this->Paginate->paginate($object, $settings);
	}


	/**
	 * Returns the query used in the overview-method of most controllers.
	 *
	 * @return \Cake\ORM\Query\SelectQuery|null
	 */
	abstract public function getOverviewQuery(): ?SelectQuery;


	/**
	 * Returns the set where-clauses used in the overview-method of most controllers.
	 *
	 * When $key is empty, the whole array is returned.
	 *
	 * When $key is set, the corresponding value is returned if set, otherwise null.
	 *
	 * @param string|null $key
	 * @param string|null $default
	 * @return mixed
	 */
	public function getOverviewWhere(?string $key = null, ?string $default = null): mixed {
		if (!isset($this->overviewWhere)) {
			$this->overviewWhere = [];
			$this->initializeOverviewWhere();
		}

		if ($key) {
			return $this->overviewWhere[ Inflector::underscore($key) ] ?? $default;
		}

		return $this->overviewWhere;
	}


	/**
	 * Sets the where-clauses used in the overview-method of most controllers.
	 *
	 * @param array|string $key
	 * @param mixed $value
	 * @return BackendController
	 * @noinspection PhpUnused
	 */
	public function setOverviewWhere(string|array $key, mixed $value = null): static {
		if (is_string($key)) {
			$this->overviewWhere[ $key ] = $value;
		}
		else {
			$this->overviewWhere = $key;
		}

		return $this;
	}


	/**
	 * Sets the initial where-clauses used in the overview-method of most controllers.
	 * This allows dynamic values to be set, depending on the state of the app.
	 *
	 * @return void
	 */
	protected function initializeOverviewWhere(): void {
	}


	/**
	 * @param string $method
	 * @return void
	 * @throws \Exception
	 */
	public function requestLock(string $method = 'update'): void {
		$this->Authorization->ensure($method);

		$lock = false;
		if ($this->request->is('post')) {
			$lock = $this->Lock->createLock((int)$this->request->getData('id'));
		}

		$this->viewBuilder()
			->setClassName('Json')
			->setOption('serialize', ['data', 'status']);

		$data = [];
		if ($lock) {
			$controller = Inflector::underscore($this->getName());

			$lockedUntil = $lock->createdOn->modify('+' . $this->Lock->getConfig('timeout') . ' seconds');

			$timezone = LocaleMiddleware::getLanguage(Awyiss::REALM_BACKEND)->timezone;

			/** @var \Awyiss\Model\Entity $entity */
			$entity = $this->fetchTable($this->defaultTable)->get($lock->foreignKey);

			$lockingUser = $lock->createdByUser?->username ?? __d('audit', 'user_system');
			/** @noinspection PhpUndefinedFieldInspection */
			if (!$lock->createdByUser && $lock->uniqueId === 'autoTranslate') {
				$lockingUser = __d('system', 'auto_translate_system');
			}

			/** @noinspection PhpPossiblePolymorphicInvocationInspection */
			$data = [
				'referenceDate' => ($entity->changedOn ?? $entity->createdOn)->format('Y-m-d H:i:s'),
				'createdOn' => $lock->createdOn->format('Y-m-d H:i:s'),
				'lockedUntil' => $lockedUntil,
				'isOwnLock' => $this->Lock->isOwnLock($lock),
				'lockWarningMessage' => __df($controller, 'locks', 'lock_warning', $lockedUntil->nice($timezone)),
				'lockTimedOutMessage' => __df($controller, 'locks', 'lock_warning_timed_out'),
				'lockedMessage' => __df($controller, 'locks', 'locked_message', $lockedUntil->nice($timezone), $lockingUser),
			];

			$this->response = $this->response->withStatus(200);
		}
		else {
			$this->response = $this->response->withStatus(500);
		}

		// Set the response data
		$this->set([
			'data' => $data,
			'status' => $lock ? 'success' : 'error',
		]);
	}


	/**
	 * @param string $method
	 * @return void
	 * @throws \Exception
	 */
	public function releaseLock(string $method = 'update'): void {
		$this->Authorization->ensure($method);

		$lock = false;
		if ($this->request->is('post')) {
			$lock = $this->Lock->releaseLock((int)$this->request->getData('id'), $this->request->getData('created_on'));
		}

		$this->viewBuilder()
			->setClassName('Json')
			->setOption('serialize', ['data', 'status']);

		// Set the response data
		$this->set([
			'data' => [],
			'status' => $lock === true ? 'success' : 'error',
		]);
	}


	/**
	 * Saves the order of the systemOrder field in the database for a given list of items.
	 *
	 * @return void
	 * @throws \Exception
	 */
	public function saveSystemOrder(): void {
		$this->Authorization->ensure('read');

		$request = Router::getRequest();

		$tableName = $this->SystemOrder->getConfig('tableName');
		$table = $this->{$tableName};

		if (!$table->hasBehavior('SystemOrder') || !$table->getBehavior('SystemOrder')->getConfig('enabled')) {
			if ($this->request->accepts('application/json')) {
				$this->viewBuilder()->setOption('serialize', ['success', 'message']);

				$this->set('success', false);
				$this->set('message', __d('system', 'system_order_not_enabled'));

				// Set the view class to JSON
				$this->viewBuilder()->setClassName('Json');

				// Setting the response status to 422 Unprocessable Entity
				$this->response = $this->response->withStatus(422, 'Unable to process entity');

				return;
			}
			else {
				$this->Flash->error(__d('system', 'system_order_not_enabled'));
				throw new RedirectException(Router::url(['action' => 'overview'], true), 302);
			}
		}

		$field = Inflector::variable($this->SystemOrder->getConfig('field', 'systemOrder'));
		if ($field !== 'systemOrder') {
			if ($this->request->accepts('application/json')) {
				$this->viewBuilder()->setOption('serialize', ['success', 'message']);

				$this->set('success', false);
				$this->set('message', __d('system', 'system_order_manual_order_is_disabled'));

				// Set the view class to JSON
				$this->viewBuilder()->setClassName('Json');

				// Setting the response status to 422 Unprocessable Entity
				$this->response = $this->response->withStatus(422, 'Unable to process entity');

				return;
			}
			else {
				$this->Flash->error(__d('system', 'system_order_manual_order_is_disabled'));
				throw new RedirectException(Router::url(['action' => 'overview'], true), 302);
			}
		}

		$affectedRows = $this->_saveSystemOrder($request->getData('order'), $table);

		if ($this->request->accepts('application/json')) {
			$this->viewBuilder()->setOption('serialize', ['success', 'message']);

			$this->set('success', true);
			$this->set('message', $affectedRows > 0 ? __d('system', 'system_order_saved') : __d('system', 'system_order_not_saved'));

			// Set the view class to JSON
			$this->viewBuilder()->setClassName('Json');
		}
		else {
			if ($affectedRows) {
				$this->Flash->success(__d('system', 'system_order_saved'));
			}
			else {
				$this->Flash->error(__d('system', 'system_order_not_saved'));
			}

			throw new RedirectException(Router::url(['action' => 'overview'], true), 302);
		}
	}


	/**
	 * Sets user configuration based on the provided url parameters and redirects to the previous page.
	 *
	 * @return void
	 * @noinspection PhpUnused
	 */
	public function userConfiguration(): void {
		$request = Router::getRequest();

		$scope = Inflector::underscore($this->getName());

		if ($scope === 'dashboard') {
			$scope = 'system';
		}

		$scope = Inflector::singularize($scope);
		$scope = Inflector::pluralize($scope);
		$scope = Inflector::underscore($scope);

		$identifier = $request->getParam('identifier') ?: $request->getData('identifier');
		$value = $request->getParam('value') ?: $request->getData('value');

		/** @var \Awyiss\Model\Entity\User $identity */
		$identity = $this->getIdentity();

		$configSettings = [
			'user_id' => $identity->id,
			'scope' => $scope,
			'identifier' => Inflector::underscore($identifier),
		];

		//Get the UserConfiguration table and fetch a matching config
		/** @var \Awyiss\Model\Table\UserConfigurationTable $table */
		$table = $this->fetchTable('UserConfiguration');
		$configEntity = $table->find()->where($configSettings)->first();

		if (!$configEntity) {
			$configEntity = $table->newDefaultEntity();
			$configSettings['value'] = $value;
			$configEntity = $table->patchEntity($configEntity, $configSettings);
		}
		else {
			$configEntity->set('value', $value);
		}

		// TODO: Delete the entity if the value is the default value of the config option

		$success = $table->save($configEntity);
		if ($success) {
			$identity->resetConfiguration();
		}

		if ($this->request->is('ajax')) {
			$this->viewBuilder()->setOption('serialize', ['success', 'message']);
			$this->set('success', !!$success);
			$this->set('message', $success ? __d('system', 'user_configuration_saved') : __d('system', 'user_configuration_not_saved'));

			// Set the view class to JSON
			$this->viewBuilder()->setClassName('Json');

			if (!$success) {
				// Setting the response status to 422 Unprocessable Entity
				$this->response = $this->response->withStatus(422, 'Unable to process entity');
			}
		}
		else {
			$referer = $request->referer();
			if ($identifier === 'paginate.limit') {
				// Remove "page:X" from the referer url
				$referer = preg_replace('/\/page:\d+/', '', $referer);

				//Remove double slashes
				$referer = preg_replace('/([^:])\/\//', '$1/', $referer);
			}

			throw new RedirectException(Router::url($referer), 302);
		}
	}


	/**
	 * beforeRender callback.
	 *
	 * @param EventInterface<\Cake\Controller\Controller> $event Event.
	 * @return void
	 */
	public function beforeRender(EventInterface $event): void {
		$this->set('designVariables', $this->getDesignVariables());

		$viewBuilder = $this->viewBuilder();
		// Disable the layout for ajax requests
		if (
			$this->request->is('ajax') &&
			($this->request->getData('reload_form') || $this->request->getParam('ajaxForm'))
		) {
			$viewBuilder->disableAutoLayout();

			// Consume the flash messages to prevent them from being displayed the next time the page is loaded
			$controller = Inflector::underscore($this->getName());
			$this->request->getFlash()->consume($controller);
		}

		if (!$this->request->is('ajax') && $this->request->getParam('overlayForm')) {
			$viewBuilder->setLayout('overlay_form');
			$viewBuilder->setVar('isOverlayForm', true);
		}
	}


	/**
	 * @param \Cake\Event\EventInterface $event
	 * @param \Psr\Http\Message\UriInterface|array|string $url
	 * @param \Cake\Http\Response $response
	 * @return void
	 */
	public function beforeRedirect(EventInterface $event, UriInterface|array|string $url, Response $response): void {
		if ($this->request->is('ajax')) {
			// Consume the flash messages to prevent them from being displayed the next time the page is loaded
			$controller = Inflector::underscore($this->getName());
			$this->request->getFlash()->consume($controller);
		}
	}


	/**
	 * @param array $requestData
	 * @param \Awyiss\Model\Table $table
	 * @return int
	 */
	protected function _saveSystemOrder(array $requestData, Table $table): int {
		/*
		 * Build an array of the order data
		 * In the first level, the key is the parent id, the value is an array of the child ids
		 * In the second level, the value is the child id, the key is the order, offset by -1
		 */
		$orderData = [];
		foreach ($requestData as $parentId => $children) {
			foreach ($children as $order => $id) {
				$orderData[] = [
					'id' => $id,
					'parentId' => $parentId === 0 ? null : $parentId,
					'systemOrder' => $order + 1,
				];
			}
		}

		$schema = $table->getSchema();

		/** @noinspection PhpUnnecessaryLocalVariableInspection */
		$affectedRows = $table->updateAll(function (QueryExpression $expression) use ($orderData, $schema) {
			$parentCase = $expression->case();
			$systemOrderCase = $expression->case();

			foreach ($orderData as $data) {
				$parentCase->when(['id' => $data['id']])->then($data['parentId'], 'integer');
				$systemOrderCase->when(['id' => $data['id']])->then($data['systemOrder'], 'integer');
			}

			if ($schema->hasColumn('parent_id')) {
				return [
					'parent_id' => $parentCase,
					'system_order' => $systemOrderCase,
				];
			}


			return [
				'system_order' => $systemOrderCase,
			];
		}, [
			'id IN' => array_column($orderData, 'id'),
		]);


		return $affectedRows;
	}


	/**
	 * Returns an array of variables, set via DesignController, that can be used in the SCSS files.
	 *
	 * @return array
	 */
	protected function getDesignVariables(): array {
		/** @var \Awyiss\Middleware\DesignMiddleware $designMiddleware */
		$designMiddleware = $this->request->getAttribute('design');

		return $designMiddleware->getDesignVariables();
	}
}
